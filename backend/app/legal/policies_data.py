class _SelfPoliciesAccessor(dict):
    """Dynamically resolves SELF_POLICIES with environment base URL (localhost vs easyfineprint.vercel.app)."""
    def __getitem__(self, key: str) -> Dict[str, Any]:
        if key in ("terms", "privacy"):
            return get_self_policy_dict(key)
        raise KeyError(key)

    def values(self):
        return [get_self_policy_dict("terms"), get_self_policy_dict("privacy")]

    def items(self):
        return [("terms", get_self_policy_dict("terms")), ("privacy", get_self_policy_dict("privacy"))]

    def keys(self):
        return ["terms", "privacy"]

    def __contains__(self, key: object) -> bool:
        return key in ("terms", "privacy")

    def __len__(self) -> int:
        return 2


SELF_POLICIES = _SelfPoliciesAccessor()


def get_self_policy(key_or_url: str) -> Optional[Dict[str, Any]]:
    """Retrieve self-policy definition dynamically for current env (localhost vs deployed vercel.app)."""
    clean = (key_or_url or "").strip().lower()
    if not clean:
        return None

    if clean in ("terms", "privacy"):
        return get_self_policy_dict(clean)

    # Parse path and domain to match localhost, vercel.app, or relative paths
    parsed = urlparse(clean)
    path = parsed.path.rstrip("/") if parsed.path else clean.rstrip("/")
    netloc = parsed.netloc.lower()

    is_terms = (
        path in ("/terms", "terms", "/terms-of-use", "terms-of-use", "/tos", "tos")
        or "terms" in clean
        or "tos" in clean
    )
    is_privacy = (
        path in ("/privacy", "privacy", "/privacy-policy", "privacy-policy")
        or "privacy" in clean
    )

    if not is_terms and not is_privacy:
        return None

    target_key = "terms" if is_terms else "privacy"

    # Relative path, scheme, or empty domain
    if not netloc:
        return get_self_policy_dict(target_key)

    # Domain match: allow localhost, 127.0.0.1, vercel.app, or easyfineprint domains
    base_origin = get_base_url().lower()
    if (
        netloc in base_origin
        or "localhost" in netloc
        or "127.0.0.1" in netloc
        or "easyfineprint.vercel.app" in netloc
        or "vercel.app" in netloc
        or "easyfineprint" in netloc
    ):
        return get_self_policy_dict(target_key)

    return None
