_RE_EFP_VERCEL_HOST = re.compile(r"^easyfineprint(?:-[a-z0-9-]+)*\.vercel\.app$")


def get_base_url() -> str:
    """Return the base URL of the active environment (easyfineprint.vercel.app or localhost:5173)."""
