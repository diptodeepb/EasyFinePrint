def _load_doc_file(filename: str, fallback: str) -> str:
    """Read document text directly from docs/ with fallback for packaged/containerized environments."""
    candidates = [
        Path(__file__).resolve().parents[3] / "docs" / filename,
        Path(__file__).resolve().parents[2] / "docs" / filename,
        Path.cwd() / "docs" / filename,
    ]
    for candidate in candidates:
        if candidate.is_file():
            try:
                content = candidate.read_text(encoding="utf-8").strip()
                if content:
                    return content
            except Exception:
                pass
    return fallback.strip()


